/**
 * Writes src/config.js from environment variables.
 *
 * A browser cannot read environment variables: they exist only on the
 * machine that runs Node. So this script runs once before the site is
 * served (locally via "npm run dev", on Vercel as the build command) and
 * copies the two PUBLIC values into a file the browser can import.
 *
 * Only the Supabase URL and anon key belong here. Secrets such as
 * SPOTIFY_CLIENT_SECRET stay in the environment and are read only by
 * the server function in /api.
 */
import { existsSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const target = fileURLToPath(new URL('../src/config.js', import.meta.url));
const { SUPABASE_URL = '', SUPABASE_ANON_KEY = '' } = process.env;
const hasValues = Boolean(SUPABASE_URL && SUPABASE_ANON_KEY);

if (!hasValues && process.env.VERCEL) {
  // Fail the deployment loudly instead of publishing a site that cannot connect.
  console.error('SUPABASE_URL and SUPABASE_ANON_KEY must be set in the Vercel project settings.');
  process.exit(1);
}

if (!hasValues && existsSync(target)) {
  console.log('No Supabase variables found; keeping the existing src/config.js.');
} else {
  // JSON.stringify produces a correctly quoted and escaped string literal.
  writeFileSync(
    target,
    [
      '// Generated by scripts/build-config.mjs. Do not edit; change .env instead.',
      `export const SUPABASE_URL = ${JSON.stringify(SUPABASE_URL)};`,
      `export const SUPABASE_ANON_KEY = ${JSON.stringify(SUPABASE_ANON_KEY)};`,
      '',
    ].join('\n'),
  );
  console.log(hasValues ? 'Wrote src/config.js.' : 'Wrote an empty src/config.js. Fill in .env to connect Supabase.');
}
